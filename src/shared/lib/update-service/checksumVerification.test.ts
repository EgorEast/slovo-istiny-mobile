import { findSha256ForAsset } from './checksumVerification'

const ASSET_NAME = 'slovo-propovedi-v0.3.0.zip'
const HASH = 'a1b2c3d4'.repeat(8)

describe('findSha256ForAsset', () => {
  test('returns the digest for a standard sha256sum line', () => {
    const sums = `${HASH}  ${ASSET_NAME}\n`

    expect(findSha256ForAsset(sums, ASSET_NAME)).toBe(HASH)
  })

  test('supports the binary-mode asterisk marker and CRLF line endings', () => {
    const sums = `${HASH} *${ASSET_NAME}\r\n`

    expect(findSha256ForAsset(sums, ASSET_NAME)).toBe(HASH)
  })

  test('matches the filename case-insensitively and normalizes the digest case', () => {
    const sums = `${HASH.toUpperCase()}  ${ASSET_NAME.toUpperCase()}\n`

    expect(findSha256ForAsset(sums, ASSET_NAME)).toBe(HASH)
  })

  test('returns null when the archive is not listed', () => {
    const sums = `${HASH}  another-file.zip\n`

    expect(findSha256ForAsset(sums, ASSET_NAME)).toBeNull()
  })

  test('returns null for a malformed checksum line', () => {
    const sums = `not-a-hash  ${ASSET_NAME}\n`

    expect(findSha256ForAsset(sums, ASSET_NAME)).toBeNull()
  })

  test('ignores blank lines and comment-like noise', () => {
    const sums = `\n# generated by CI\n${HASH}  ${ASSET_NAME}\n`

    expect(findSha256ForAsset(sums, ASSET_NAME)).toBe(HASH)
  })
})
